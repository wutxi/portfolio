def recommend(taste: str, when: str, budget: str, limit: int = 3) -> list[Product]:
    max_price = {"600": 600, "1000": 1000}.get(budget, 10 ** 9)
    scored = []
    for p in PRODUCTS:
        if p.cat == "ware":
            continue
        if when == "evening" and p.caffeine:
            continue
        s = 3 if p.taste == taste else 0
        if when == "morning":
            s += p.caffeine
        elif when == "day":
            s += 1 if p.caffeine == 1 else 0
        if p.price <= max_price:
            s += 2
        else:
            s -= 3
        scored.append((s, -p.price, p))
    scored.sort(key=lambda x: (x[0], x[1]), reverse=True)
    return [p for _s, _neg, p in scored[:limit]]


def catalog_for_prompt() -> str:
    lines = [f"- {p.name} ({CATEGORIES[p.cat]}), {p.price} ₽ за {p.pack}: {p.desc}" for p in PRODUCTS]
    faq = [f"- {t}: {a}" for t, a in FAQ.values()]
    return "Каталог:\n" + "\n".join(lines) + "\n\nУсловия магазина:\n" + "\n".join(faq)
