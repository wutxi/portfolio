def cards_slide(d: Deck, kicker, title, cards, *, numbered=True, y=2.9, h=3.75, title_size=18, body_size=14,
                title_h=0.75, head_size=36):
    d.slide()
    d.heading(title, kicker, size=head_size)
    n = len(cards)
    gap = 0.3
    w = (12.13 - gap * (n - 1)) / n
    for i, (ttl, body) in enumerate(cards):
        d.card(0.6 + i * (w + gap), y, w, h, ttl, body, num=(i + 1) if numbered else None, title_size=title_size,
               body_size=body_size, title_h=title_h)


def tasks_slide(d: Deck, kicker, title, tasks):
    d.slide()
    d.heading(title, kicker, size=32)
    for i, (num, name, result, prompt) in enumerate(tasks):
        x = 0.6 + i * 6.22
        d.badge(x, 2.2, 0.62, str(num), size=18)
        d.h(x + 0.8, 2.2, 5.1, 0.62, name, 20, anchor="m")
        d.text(x, 3.0, 5.9, 0.6, [[("Что получаете: ", {"color": d.t.text, "bold": True}), (result, {})]], 13,
               color=d.t.muted)
        d.prompt_box(x, 3.75, 5.9, 3.0, prompt, size=14)


def flow_slide(d: Deck, kicker, title, steps, note=None, *, y=2.7):
    t = d.t
    d.slide()
    d.heading(title, kicker)
    n = len(steps)
    if t.rounded:
        gap = 0.35
        w = (12.13 - gap * (n - 1)) / n
        for i, (label, desc) in enumerate(steps):
            x = 0.6 + i * (w + gap)
            sh = d.box(x, y, w, 1.0, fill=t.acc if i % 2 == 0 else t.acc2)
            d.h(0, 0, 0, 0, label, 16, color=t.on_acc, align="c", anchor="m", shape=sh)
            if i < n - 1:
                d.h(x + w, y, gap, 1.0, "›", 26, color=t.acc, align="c", anchor="m")
            d.text(x + 0.1, y + 1.3, w - 0.2, 1.9, desc, 13, color=t.muted)
    else:
        w = (12.13 + 0.25 * (n - 1)) / n
        for i, (label, desc) in enumerate(steps):
            x = 0.6 + i * (w - 0.25)
            kind = MSO_SHAPE.PENTAGON if i == 0 else MSO_SHAPE.CHEVRON
            sh = d.shape(x, y, w, 1.0, fill=t.acc if i % 2 == 0 else t.acc2, kind=kind, adj=0.35)
            d.h(0, 0, 0, 0, label, 16, color=t.on_acc, align="c", anchor="m", shape=sh)
            d.text(x + 0.2, y + 1.3, w - 0.6, 1.9, desc, 13, color=t.muted)
    if note:
        d.box(0.6, 5.75, 12.13, 0.95, fill=t.panel)
        d.shape(0.6, 5.75, 0.07, 0.95, fill=t.acc)
        d.text(0.95, 5.75, 11.6, 0.95, note, 14, anchor="m")


def week_slide(d: Deck, num, days, title, goal, rows):
    t = d.t
    d.slide(footer_x=4.2)
    if t.name == "editorial":
        d.shape(0, 0, 3.6, 7.5, fill=t.panel)
        d.shape(3.6, 0, 0.02, 7.5, fill=t.dim)
        ink, txt = t.acc, t.text
    else:
        d.shape(0, 0, 3.6, 7.5, fill=t.acc)
        ink = txt = t.acc_ink
    d.h(0.5, 0.6, 2.8, 0.35, "НЕДЕЛЯ", 14, color=txt)
    d.h(0.5, 0.95, 2.8, 2.0, num, 120, color=ink, spacing=0.9)
    d.text(0.5, 3.15, 2.8, 0.4, days, 14, color=txt, bold=True)
    d.text(0.5, 4.6, 2.7, 2.0, [[("Цель недели\n", {"bold": True, "font": t.head, "size": 12})], goal], 15, color=txt)
    d.h(4.2, 0.6, 8.6, 1.4, title, 36)
    y = 2.05
    for when, what, how in rows:
        d.box(4.2, y, 8.53, 1.08, fill=t.panel)
        d.text(4.45, y, 1.45, 1.08, when, 13, color=t.acc, bold=True, anchor="m")
        d.h(5.95, y + 0.14, 6.6, 0.4, what, 16)
        d.text(5.95, y + 0.55, 6.6, 0.48, how, 12, color=t.muted)
        y += 1.2


def closing_slide(d: Deck, title, items, footer):
    t = d.t
    d.slide()
    d.shape(0, 0, 13.333, 0.12, fill=t.acc)
    d.heading(title, "Что дальше", y=0.7, size=40)
    y = 2.75
    for i, item in enumerate(items):
        d.badge(0.6, y, 0.55, str(i + 1), size=16)
        d.text(1.4, y, 11.2, 0.55, item, 18, anchor="m")
        y += 0.8
    d.text(0.6, 6.25, 12.1, 0.5, footer, 14, color=t.muted)


